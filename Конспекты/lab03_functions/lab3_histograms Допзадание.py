#
# Здесь используем код символа непосредственно как индекс. Поэтому для кода `ord('z')` нужна ячейка с таким индексом, а длина списка должна быть на единицу больше. Пример рассчитан на строчные латинские буквы. <br>
# ```
# Если сдвигать индекс на единицу (`ord(char) - 1`), то при выводе нужно восстанавливать символ как `chr(index + 1)`. Смешивать индекс и код символа нельзя: цикл по `range(ord('z'))` не достигает кода `z`, а индекс `-1` обращается к последней ячейке.
