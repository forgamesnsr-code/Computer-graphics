# ## 2.1. Построение группированного (интервального) статистического ряда
#
# Группированным    (интервальным)    статистическим   рядом
# называется совокупность промежутков (частичных интервалов) ∆1,
# ∆2,…,∆к и соответствующих им частот n1, n2,…,nк.
#
# ### 2.1.1. Выбор количества промежутков k интервального ряда
# При слишком большом k картина распределения будет искажена
# случайными колебаниями частот; при слишком малом k будут сглажены
# и затушеваны характерные особенности распределения. От k зависит
# объем вычислительных работ.
# Следовательно, удачно подобранное k порождает и "удачный" ряд.
# Рекомендации относительно выбора k различны. Например, можно
# воспользоваться правилом Старджесса:
# k = 1+3,3lgn, если n≤100;
# k = 5lgn, если n>100, где n - число наблюдений (объем выборки).
# В нашем случае n=100; k =1+3,3×2≈8.
# Итак, в нашем случае, оптимальное количество частичных
# интервалов (промежутков) k=8.
#
# ### 2.1.2. Определение ширины h частичного интервала
# Логично h определять по формуле h=( xmax – xmin ) / k, где xmax и xmin -
# наименьшее и наибольшее (60 и 81) числа выборки. В любом случае
# ширина интервала не должна быть меньше цены деления
# измерительного прибора.
# R= xmax – xmin называется размахом или широтой выборки. Но
# частное от деления R на k часто приходится округлять! С недостатком
# или с избытком? Если с избытком, то приходится увеличить R на 2∆
# (рис.1).

# %% [markdown]
# ![image.png](attachment:de40b74c-c46a-4913-ab24-4cc210f5b84d.png)
# [Рис. 1: размах выборки расширяется на Δ с каждой стороны; новая длина равна R + 2Δ.]
#
# «Удачный» статистический ряд получается, если стремиться к тому,
# чтобы границы частичных интервалов не совпадали с наблюдаемыми
# значениями. Этого добиваются за счет незначительного расширения
# интервала наблюдаемых значений, для чего округляют полученное
# значение h с избытком до наиболее удобного числа. Например, если
# наблюдаемые значения - целые числа, то округляют до десятых. Тогда Δ
# можно определить по формуле Δ = ( h∙k – (xmax–xmin ) ) / 2.
# Выбор Δ зависит от конкретных данных и цели обработки. Во
# многих случаях выбор h диктуется природой измеряемой величины.
# Часто Δ берут равным h/2, но тогда число интервалов l может оказаться
# больше. При упрощенной обработке Δ берут равным нулю. В нашем
# случае возьмем Δ равным точности измерения. Так как все значения
# выборки – целые числа, точность измерения 0,5, то есть пусть Δ=0,5.
# Тогда     имеем      весь интервал  значений        [59,5;81,5]  и
# h = (81,5–59,5)/8 = 2,75.
# Итак, выбираем ширину промежутка (частичного интервала)
# h= 2,75.
#
# ### 2.1.3. Определение границ частичных интервалов
# Границы частичных интервалов определяются по формуле
# x0 = xmin – Δ; xi = xi–1 + h
# В нашем случае получим следующие границы:
# 59,5; 62,25; 65; 67,75; 70,5 и так далее.
#
# ### 2.1.4. Определение частот ni
# Если не удается избежать совпадения измеренных значений с
# границами промежуточных интервалов, то в таких случаях эти значения
# часто рекомендуется делить пополам, т.е. половину таких значений
# относить к левому, а половину - к правому интервалу, что мы и
# будем делать. Чтобы не иметь дело с дробями при нечетном
# количестве значений, совпадающих с границей интервалов,
# договоримся относить «лишнее» значение к правому интервалу.
# Очень трудно сразу, без ошибок, правильно сосчитать частоты ni,
# поэтому рекомендуем записывать все карандашом и, последовательно
# просматривая данные таблицы, ставить палочку напротив записанного
# числа столько раз, сколько раз оно встретилось. Для удобства 5 палочек
# перечеркнем горизонталью, получив так называемый «пяток».
# Выполним контроль: ∑ni= 100. Середину i-го интервала хi получаем
# прибавлением к левой границе h/2≈1,4.
# Этот процесс отображен в табл. 2.
