# %%
data = 'aaabbc'

freqs = [0] * (ord('z') + 1)

for char in data:
    freqs[ord(char)] += 1

print(freqs)

for char_code in range(len(freqs)):
    if freqs[char_code] != 0:
        print(chr(char_code), '-->', freqs[char_code], 'раза')
