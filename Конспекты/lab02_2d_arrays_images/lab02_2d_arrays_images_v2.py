# **Новые понятия:** `opencv_rectangle`, `drawing_thickness`.
#
# #### Математическая модель
#
# Прямоугольник зададим двумя противоположными углами:
#
# $$A=(x_1,y_1),\qquad B=(x_2,y_2).$$
#
# #### Числовой пример
#
# $$A=(40,30),\qquad B=(190,120).$$
