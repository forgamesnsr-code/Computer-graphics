# **Новые понятия:** `color_image`, `bgr_rgb_order`.
#
# #### Математическая модель
#
# Форма цветного изображения:
#
# $$H\times W\times 3.$$
#
# В OpenCV тройка записывается в порядке:
#
# $$(B,G,R).$$
#
# #### Числовой пример
#
# Красный цвет в OpenCV:
#
# $$(B,G,R)=(0,0,255).$$

