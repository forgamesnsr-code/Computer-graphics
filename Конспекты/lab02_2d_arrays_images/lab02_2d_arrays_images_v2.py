# **Новое понятие:** `opencv_circle`.
#
# #### Математическая модель
#
# Окружность с центром $(x_0,y_0)$ и радиусом $R$:
#
# $$(x-x_0)^2+(y-y_0)^2=R^2.$$
#
# #### Числовой пример
